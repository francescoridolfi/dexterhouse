"""Registry files: `packages/<name>.json` (author PRs) and the generated `index.json`."""

import itertools
from datetime import datetime
from typing import Annotated

from pydantic import Field, StringConstraints, model_validator

from dexterhouse_schema.common import (
    GithubUser,
    HttpUrl,
    PackageName,
    SchemaVersion,
    SemVer,
    StrictModel,
    VersionRange,
)
from dexterhouse_schema.manifest import PackageKind, Tag
from dexterhouse_schema.semver import SemanticVersion
from dexterhouse_schema.tool import Risk

Sha256 = Annotated[str, StringConstraints(pattern=r"^[0-9a-f]{64}$")]
GitRef = Annotated[str, StringConstraints(min_length=1, max_length=255)]
Timestamp = Annotated[datetime, Field(strict=False)]


def _check_versions(versions: list[str]) -> None:
    """Versions are unique and listed in increasing semver order."""
    parsed = [SemanticVersion(v) for v in versions]
    for prev, cur in itertools.pairwise(parsed):
        if not prev < cur:
            raise ValueError(f"versions must be strictly increasing: {prev.text} then {cur.text}")


class IndexVersion(StrictModel):
    version: SemVer
    ref: GitRef
    sha256: Sha256
    compat_core: VersionRange


class PublishedVersion(IndexVersion):
    published_at: Timestamp
    signature: str | None = None


class RegistryPackage(StrictModel):
    """`packages/<name>.json`; the file stem must equal `name` (checked by the loader)."""

    schema_version: SchemaVersion = Field(alias="schema")
    name: PackageName
    kind: PackageKind
    repo: HttpUrl
    author_github: GithubUser
    versions: Annotated[list[PublishedVersion], Field(min_length=1)]
    verified: bool = False
    deprecated: bool = False
    replaced_by: PackageName | None = None

    @model_validator(mode="after")
    def _check(self) -> "RegistryPackage":
        _check_versions([v.version for v in self.versions])
        if self.replaced_by == self.name:
            raise ValueError("replaced_by must name another package")
        return self


def check_registry_update(
    old: RegistryPackage | None, new: RegistryPackage, *, by_maintainer: bool = False
) -> list[str]:
    """CI rules on a PR that changes `packages/<name>.json`; returns error messages.

    Published versions are immutable and never removed, new versions are greater than
    the last published one, `verified` / `deprecated` change only through a maintainer.
    """
    errors: list[str] = []
    if old is None:
        if not by_maintainer and (new.verified or new.deprecated):
            errors.append("verified/deprecated can only be set by a maintainer")
        return errors
    if (old.name, old.kind) != (new.name, new.kind):
        errors.append("name and kind cannot change")
    new_by_version = {v.version: v for v in new.versions}
    for published in old.versions:
        current = new_by_version.get(published.version)
        if current is None:
            errors.append(f"published version {published.version} cannot be removed")
        elif current != published:
            errors.append(f"published version {published.version} cannot be modified")
    last = SemanticVersion(old.versions[-1].version)
    known = {v.version for v in old.versions}
    for added in (v for v in new.versions if v.version not in known):
        if not SemanticVersion(added.version) > last:
            errors.append(f"new version {added.version} must be greater than {last.text}")
    if not by_maintainer and (old.verified, old.deprecated) != (new.verified, new.deprecated):
        errors.append("verified/deprecated can only be changed by a maintainer")
    return errors


class IndexEntry(StrictModel):
    name: PackageName
    kind: PackageKind
    description: Annotated[str, StringConstraints(max_length=200)]
    tags: Annotated[list[Tag], Field(max_length=10)] = Field(default_factory=list)
    author_github: GithubUser
    verified: bool
    latest: SemVer
    versions: Annotated[list[IndexVersion], Field(min_length=1)]
    repo: HttpUrl
    risk: Risk = Field(description="Highest permission risk (tools) or of the required tools.")

    @model_validator(mode="after")
    def _check(self) -> "IndexEntry":
        versions = [v.version for v in self.versions]
        _check_versions(versions)
        if self.latest != versions[-1]:
            raise ValueError(f"{self.name}: latest must be the highest version ({versions[-1]})")
        return self


class RegistryIndex(StrictModel):
    """`index.json`, generated by the registry CI."""

    schema_version: SchemaVersion = Field(alias="schema")
    generated_at: Timestamp
    core_latest: SemVer
    packages: list[IndexEntry]

    @model_validator(mode="after")
    def _unique(self) -> "RegistryIndex":
        names = [p.name for p in self.packages]
        dupes = sorted({n for n in names if names.count(n) > 1})
        if dupes:
            raise ValueError(f"duplicate package(s) in index: {', '.join(dupes)}")
        return self
